#!/usr/bin/env python3
"""Build a self-contained Kaggle script kernel that embeds this repo (base64 tar.gz) and runs a
command on the competition data. One `kaggle kernels push` per experiment, no dataset versioning.

    python kaggle/build_kernel.py --slug filanet-cv4 --cmd "python scripts/train_folds.py --data-dir {DATA} \
        --out-root /kaggle/working/runs --cache-dir /tmp/targets"
    kaggle kernels push -p kaggle/out/filanet-cv4 --accelerator NvidiaL4X4
"""
import argparse
import base64
import io
import json
import os
import tarfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEMPLATE = r'''# Auto-generated by kaggle/build_kernel.py -- FilaNet experiment runner
import base64, glob, io, os, subprocess, sys, tarfile, time
t0 = time.time()
CODE = "/kaggle/tmp_code"
os.makedirs(CODE, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz").extractall(CODE)
print(subprocess.run(["nvidia-smi", "-L"], capture_output=True, text=True).stdout, "cpus", os.cpu_count(), flush=True)
PIP = PIP_PKGS
if PIP:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q"] + PIP, check=False)
cands = [p for p in glob.glob("/kaggle/input/**/MAGFiLO_1.0_Kaggle_2026", recursive=True) if os.path.isdir(p)]
DATA = cands[0] if cands else "/kaggle/input"
print("DATA", DATA, flush=True)
INPUTS = {os.path.basename(p): p for p in glob.glob("/kaggle/input/*/*") + glob.glob("/kaggle/input/*")}
cmds = CMDS
env = dict(os.environ, PYTHONPATH=CODE, HF_HUB_DISABLE_PROGRESS_BARS="1")
for c in cmds:
    c = c.replace("{DATA}", DATA)
    print(">>>", c, flush=True)
    r = subprocess.run(c, shell=True, cwd=CODE, env=env)
    print("<<< exit", r.returncode, f"{(time.time() - t0) / 60:.1f} min", flush=True)
print("total minutes", (time.time() - t0) / 60)
'''


def make_payload() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for sub in ["filanet", "scripts", "weights", "requirements.txt"]:
            p = os.path.join(ROOT, sub)
            if not os.path.exists(p):
                continue
            tar.add(p, arcname=sub, filter=lambda ti: None if ("__pycache__" in ti.name or ti.name.endswith(".pyc")
                                                                   or ti.size > 30_000_000) else ti)
    return base64.b64encode(buf.getvalue()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True)
    ap.add_argument("--user", default="dasshovon")
    ap.add_argument("--cmd", action="append", required=True)
    ap.add_argument("--pip", nargs="*", default=[])
    ap.add_argument("--datasets", nargs="*", default=[])
    ap.add_argument("--kernels", nargs="*", default=[])
    ap.add_argument("--models", nargs="*", default=[])
    ap.add_argument("--no-gpu", action="store_true")
    a = ap.parse_args()
    out = os.path.join(ROOT, "kaggle", "out", a.slug)
    os.makedirs(out, exist_ok=True)
    src = TEMPLATE.replace("PAYLOAD", repr(make_payload())).replace("CMDS", repr(a.cmd)).replace("PIP_PKGS", repr(a.pip))
    open(os.path.join(out, "run.py"), "w").write(src)
    meta = dict(id=f"{a.user}/{a.slug}", title=a.slug, code_file="run.py", language="python", kernel_type="script",
                is_private=True, enable_gpu=not a.no_gpu, enable_internet=True, dataset_sources=a.datasets,
                competition_sources=["filament-segmentation-2026"], kernel_sources=a.kernels, model_sources=a.models)
    json.dump(meta, open(os.path.join(out, "kernel-metadata.json"), "w"), indent=1)
    print(out, f"{os.path.getsize(os.path.join(out, 'run.py')) / 1e3:.0f} KB")


if __name__ == "__main__":
    main()
